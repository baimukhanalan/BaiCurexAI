
import { GoogleGenAI } from "@google/genai";
import { StudyType, QuantitativeData, ProcessedResponse, TriageStatus, RiskLevel } from "../types";

export const generateAIClinicalReport = async (
  type: StudyType, 
  data: QuantitativeData,
  age: number,
  gender: string
): Promise<string> => {
  // Always initialize GoogleGenAI inside the function right before making an API call to ensure use of the correct environment variable.
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });

  const prompt = `
    Generate a professional medical clinical summary for a ${type} study.
    Patient: ${age} years old, ${gender}.
    Quantitative Data: ${JSON.stringify(data)}.
    
    Guidelines:
    - Use professional medical terminology.
    - Be neutral.
    - Do NOT provide any diagnosis.
    - Do NOT suggest treatments or medications.
    - Describe the patterns and rhythms found in the data.
    - Mention signal quality.
    - End with a standard disclaimer: "This report is generated by a Decision Support System and requires clinical correlation by the attending physician."
  `;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-3-flash-preview',
      contents: prompt,
      config: {
        systemInstruction: "You are a medical reporting assistant for a Decision Support System. You convert mathematical features of EEG and ECG signals into neutral, descriptive medical text for clinicians. Do NOT diagnose."
      }
    });

    return response.text || "Report generation failed.";
  } catch (error) {
    console.error("AI Report Generation Error:", error);
    return "Error generating clinical summary. Please refer to quantitative data.";
  }
};

/**
 * Mocks the Backend mathematical analysis process.
 * In a real scenario, this would happen on the Python server.
 */
export const simulateBackendProcessing = async (
  type: StudyType,
  age: number,
  gender: string,
  fileName: string
): Promise<ProcessedResponse> => {
  // Simulate heavy math processing time
  await new Promise(resolve => setTimeout(resolve, 2000));

  let quantitative_data: QuantitativeData;
  let triage_status: TriageStatus = TriageStatus.GREEN;
  let risk_level: RiskLevel = RiskLevel.LOW;
  let auditor_required = false;

  // Mocked rule-based logic based on random "discovered" features
  if (type === StudyType.EEG) {
    const isAbnormal = Math.random() > 0.7;
    const isCritical = isAbnormal && Math.random() > 0.6;
    
    quantitative_data = {
      quality_index: 0.85 + Math.random() * 0.1,
      triage_reasons: [],
      dominant_rhythm: isAbnormal ? "Theta" : "Alpha",
      alpha_percent: isAbnormal ? 40 : 85,
      theta_percent: isAbnormal ? 45 : 10,
      delta_percent: isAbnormal ? 10 : 5,
      beta_percent: 5,
      slowing_detected: isCritical
    };

    if (isCritical) {
      triage_status = TriageStatus.RED;
      risk_level = RiskLevel.HIGH;
      auditor_required = true;
      quantitative_data.triage_reasons.push("Critical slowing detected");
    } else if (isAbnormal) {
      triage_status = TriageStatus.YELLOW;
      risk_level = RiskLevel.MODERATE;
      auditor_required = true;
      quantitative_data.triage_reasons.push("Background rhythm deviations");
    } else {
      quantitative_data.triage_reasons.push("Normal background activity");
    }
  } else {
    // ECG Mock
    const heartRate = 60 + Math.floor(Math.random() * 80);
    const irregular = Math.random() > 0.8;
    
    quantitative_data = {
      quality_index: 0.92,
      triage_reasons: [],
      hr: heartRate,
      hrv: 45 + Math.random() * 20,
      rr_variance: irregular ? 0.15 : 0.02,
      arrhythmia_pattern: irregular ? "PVC detected" : null
    };

    if (heartRate > 130 || heartRate < 45) {
      triage_status = TriageStatus.RED;
      risk_level = RiskLevel.HIGH;
      auditor_required = true;
      quantitative_data.triage_reasons.push("Extreme heart rate");
    } else if (irregular) {
      triage_status = TriageStatus.YELLOW;
      risk_level = RiskLevel.MODERATE;
      auditor_required = true;
      quantitative_data.triage_reasons.push("Cardiac rhythm irregularity");
    } else {
      quantitative_data.triage_reasons.push("Normal sinus rhythm");
    }
  }

  const ai_report = await generateAIClinicalReport(type, quantitative_data, age, gender);

  return {
    study_type: type,
    triage_status,
    risk_level,
    ai_report,
    quantitative_data,
    auditor_required,
    pdf_url: `https://storage.googleapis.com/baicurex-reports/report_${Date.now()}.pdf`
  };
};